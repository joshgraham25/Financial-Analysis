"""Turn prepared frames + a lines file into a silent recording and a beats table.

This is the front half of the driven-capture pipeline that produced 003. Nothing is recorded
in real time: each screen is held for exactly as long as Andrew takes to read its line, so the
picture and the narration cannot drift.

    python assemble_capture.py --episode 3 --frames frames/clean --map frames/map.txt

`--map` is one frame name per spoken line, in order, blank lines and # comments ignored. Fewer
entries than there are lines is how the outro works: the trailing lines have no frame, so they
land past the end of the picture and play over the recap card.

Outputs, next to the frames:
  * `concat.txt`     -- ffmpeg concat list with per-frame durations
  * `picture_len`    -- exact length of the picture, in seconds
  * `<episode>/beats.md` -- caption times for overlay_episode.py

Then:
    ffmpeg -f concat -safe 0 -i concat.txt -t $(cat picture_len) \\
           -vf "fps=30,format=yuv420p" -c:v libx264 -crf 16 -preset slow \\
           -tune stillimage raw.mp4
    python overlay_episode.py --episode N --video raw.mp4 --crf 10

**The -t is not optional.** ffmpeg's concat demuxer holds the final frame to fill, so without
it the picture overruns and lines meant for the recap card play over a static screen instead.
That shipped once.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import subprocess
import sys
from pathlib import Path

try:
    import edge_tts
except ImportError:
    sys.exit("pip install edge-tts pillow")

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
VOICE = "en-US-AndrewNeural"
GAP = 0.45          # air between lines, matching overlay_episode's VOICE_PAD budget


def episode_dir(number: int) -> Path:
    cat = json.loads((ROOT / "episodes.json").read_text(encoding="utf-8"))
    eps = cat["episodes"] if isinstance(cat, dict) else cat
    for e in eps:
        if e.get("number") == number:
            return ROOT / "episodes" / e["slug"]
    sys.exit(f"episode {number} is not in episodes.json")


def read_lines(path: Path) -> list[str]:
    body = path.read_text(encoding="utf-8")
    body = body.split("\n---\n", 1)[1] if "\n---\n" in body else body
    return [l.strip() for l in body.splitlines() if l.strip()]


def read_map(path: Path) -> list[str]:
    out = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


async def speak(line: str, dest: Path) -> float:
    await edge_tts.Communicate(line, VOICE).save(str(dest))
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", str(dest)], capture_output=True, text=True).stdout.strip()
    return float(out)


async def run(args) -> None:
    ep = episode_dir(args.episode)
    frames = Path(args.frames)
    names = read_map(Path(args.map))
    lines = read_lines(Path(args.lines) if args.lines else ep / "lines.md")

    if len(names) > len(lines):
        sys.exit(f"{len(names)} frames but only {len(lines)} lines")
    outro = len(lines) - len(names)
    missing = [n for n in set(names) if not (frames / f"{n}.png").exists()]
    if missing:
        sys.exit("missing frames: " + ", ".join(sorted(missing)))

    voice = frames.parent / "voice"
    voice.mkdir(parents=True, exist_ok=True)
    durations = [await speak(l, voice / f"l{i:02d}.mp3") for i, l in enumerate(lines, 1)]

    rows, t, beats = [], 0.0, []
    for i, name in enumerate(names):
        hold = durations[i] + GAP
        rows.append(f"file '{(frames / f'{name}.png').resolve().as_posix()}'\nduration {hold:.3f}")
        beats.append((round(t, 2), lines[i]))
        t += hold
    picture = t
    rows.append(f"file '{(frames / f'{names[-1]}.png').resolve().as_posix()}'")

    for j in range(len(names), len(lines)):          # spoken over the recap card
        beats.append((round(t, 2), lines[j]))
        t += durations[j] + GAP

    (frames.parent / "concat.txt").write_text("\n".join(rows) + "\n", encoding="utf-8")
    (frames.parent / "picture_len").write_text(f"{picture:.3f}", encoding="utf-8")

    doc = ["# Caption beats", "",
           "Generated by `production/assemble_capture.py`. Real screens driven in the browser,",
           "each held for exactly as long as Andrew takes to read its line.", "",
           "| Start | Text |", "| --- | --- |"]
    doc += [f"| {s} | {txt} |" for s, txt in beats]
    (ep / "beats.md").write_text("\n".join(doc) + "\n", encoding="utf-8")

    print(f"{len(names)} frames, {len(lines)} lines ({outro} over the card)")
    print(f"picture {picture:.1f}s -> trim with -t {picture:.3f}; with outro {t:.1f}s")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--episode", type=int, required=True)
    ap.add_argument("--frames", required=True, help="directory of prepared frames")
    ap.add_argument("--map", required=True, help="one frame name per spoken line, in order")
    ap.add_argument("--lines", default=None, help="default: <episode>/lines.md")
    asyncio.run(run(ap.parse_args()))


if __name__ == "__main__":
    main()
